// Regenerates src/renderer/model-logos.js from the simple-icons package.
//
// Run with:  npm i --no-save simple-icons && node scripts/gen-model-logos.js
//
// The paths are vendored rather than imported so the app stays self-contained
// (the renderer's CSP forbids external fetches) and ships no runtime dependency.
// Only the brands actually used are extracted.
//
// Licensing: simple-icons' icon data is CC0. The marks themselves remain the
// trademarks of their owners; Axon uses them nominatively, to identify which
// model family a row refers to, which implies no affiliation or endorsement.
// Brands the icon set deliberately does not carry — Microsoft, IBM, OpenAI —
// are NOT sourced from anywhere else. They keep Axon's own neutral glyph.
const fs = require('fs');
const path = require('path');
const si = require('simple-icons');

const WANTED = [
  ['meta', 'siMeta'],
  ['qwen', 'siQwen'],
  ['deepseek', 'siDeepseek'],
  ['mistral', 'siMistralai'],
  ['gemini', 'siGooglegemini'],
  ['google', 'siGoogle'],
  ['ollama', 'siOllama'],
  ['huggingface', 'siHuggingface'],
  ['anthropic', 'siAnthropic'],
];

const brands = {};
for (const [key, slug] of WANTED) {
  const icon = si[slug];
  if (!icon) { console.error('missing icon: ' + slug); process.exit(1); }
  brands[key] = { title: icon.title, hex: '#' + icon.hex, path: icon.path };
}

const out = `// GENERATED by scripts/gen-model-logos.js -- do not edit by hand.
//
// Official brand marks, vendored from simple-icons (icon data: CC0). Each mark
// remains the trademark of its owner and is used here only to identify the
// model family a row belongs to; that implies no affiliation or endorsement.
// Paths are 24x24 and meant to be FILLED, not stroked.
//
// Microsoft (Phi), IBM (Granite) and OpenAI are intentionally absent: the CC0
// set does not carry them, so those families keep Axon's own neutral glyph
// rather than an imitation.
const BRAND_LOGOS = ${JSON.stringify(brands, null, 2)};
`;

const target = path.join(__dirname, '..', 'src', 'renderer', 'model-logos.js');
fs.writeFileSync(target, out);
console.log('wrote ' + target + ' (' + Object.keys(brands).length + ' brands, ' + out.length + ' bytes)');
